# ווינדוס לא מרשה " * : < > ? \ | בשם קובץ, וכונן G: מחליף אותם בתווים פרטיים (U+F0xx).
# למשל ד"ר נשמר כ-ד<U+F022>ר. מחזירים לתו המקורי לתצוגה.
UNPUA = {0xF000 + ord(c): c for c in '"*:<>?\\|'}


def fix_chars(s):
    return s.translate(UNPUA)


_num = re.compile(r"^(\d+)\s*-\s*")
_junk = re.compile(r"^(שונות( מסווג)?( - .*)?|פרקים [א-ת]'?|קבצים ממוספרים.*|בית הספר ל|א-ת - .*|המדרשה [א-ת]')$")


def _key(s):
    return re.sub(r"[\W_]+", "", s)


def _clean_segs(segs, topic):
    out, letter = [], ""
    for seg in segs:
        m = re.match(r"^א-ת - (.+)$", seg)
        if m:
            letter = m.group(1)
            continue
        seg = _num.sub("", seg).strip()
        if not seg or _junk.match(seg):
            continue
        seg = re.sub(r"^שיעורים כלליים( - .*)?$", "שיעורים כלליים", seg)
        if seg in ALIAS:
            seg = ALIAS[seg]
            if not seg:
                continue
        seg = re.sub(r"^דר ", 'ד"ר ', seg)
        if out and seg.startswith(out[-1] + " - "):        # "שלמה קרליבך / שלמה קרליבך - אוסף שירים"
            seg = seg[len(out[-1]) + 3:]
        if out and _key(seg) in _key(out[-1]):
            continue                                          # שכבה כפולה באותו שם
        if out and _key(out[-1]) in _key(seg):
            out[-1] = seg                                     # "גלעד פוטולסקי" → "שלהבת וגלעד פוטולסקי"
            continue
        if _key(seg) and _key(seg) in _key(NAMES[topic]):
            continue                                          # שם הנושא עצמו
        out.append(seg)
    return " · ".join(out[:2]), letter


def place(rel):
    """נתיב יחסי (מפריד \\) → (topic_id, group, letter)."""
    segs = fix_chars(rel).split("\\")[:-1]
    top = segs[0]
    m = _num.match(top)
    n = m.group(1) if m else ""
    rest = segs[1:]
    extra = ""
    if n == "99" or top.startswith("שירים"):
        sm = _num.match(rest[0]) if rest else None
        sn = sm.group(1) if sm else ""
        if top.startswith("שירים"):
            topic = SUB_SONGS.get(sn, "singers")
            rest = rest[1:]
        else:
            topic = SUB99.get(sn, "misc")
            g = SUB99_GROUP.get(sn)
            if g is not None:
                extra = g
                rest = rest[1:]
            else:
                rest = rest[1:]
    else:
        topic = TOP.get(n, "misc")
        extra = TOP_GROUP.get(n, "")
    group, letter = _clean_segs(rest, topic)
    first = group.split(" · ")[0]
    if first in GROUP_TOPIC:
        topic = GROUP_TOPIC[first]
    if extra:
        group = extra + (" · " + group if group and group != "שיעורים כלליים" else "")
    group = re.sub(r"(^|· )דר\s+", r'\1ד"ר ', group)
    return topic, group, letter
